"""
database/database.py - Database initialization and connection management
VPN Health and Security Monitor
"""

import sqlite3
import logging
import os
from config import config

logger = logging.getLogger(__name__)


def get_db_connection():
    """Get a database connection with row factory for dict-like access."""
    conn = sqlite3.connect(config.DATABASE_PATH)
    conn.row_factory = sqlite3.Row  # Allows accessing columns by name
    conn.execute("PRAGMA foreign_keys = ON")  # Enable foreign key support
    return conn


def init_db():
    """
    Initialize the database and create all required tables.
    Called once when the application starts.
    """
    logger.info("Initializing database...")
    conn = get_db_connection()
    cursor = conn.cursor()

    # -------------------------------------------------------
    # Table: vpn_servers
    # Stores information about monitored VPN servers
    # -------------------------------------------------------
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS vpn_servers (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            name        TEXT NOT NULL,
            hostname    TEXT NOT NULL,
            vpn_type    TEXT NOT NULL DEFAULT 'OpenVPN',
            location    TEXT,
            port        INTEGER DEFAULT 1194,
            status      TEXT DEFAULT 'unknown',
            created_at  TEXT DEFAULT (datetime('now')),
            updated_at  TEXT DEFAULT (datetime('now'))
        )
    """)

    # -------------------------------------------------------
    # Table: vpn_logs
    # Stores VPN login/logout/connection log entries
    # -------------------------------------------------------
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS vpn_logs (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            timestamp   TEXT NOT NULL,
            username    TEXT,
            source_ip   TEXT,
            server_name TEXT,
            event_type  TEXT,
            status      TEXT,
            reason      TEXT,
            location    TEXT,
            session_id  TEXT,
            created_at  TEXT DEFAULT (datetime('now'))
        )
    """)

    # -------------------------------------------------------
    # Table: alerts
    # Stores security alerts generated by the analyzer
    # -------------------------------------------------------
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS alerts (
            id           INTEGER PRIMARY KEY AUTOINCREMENT,
            timestamp    TEXT NOT NULL,
            severity     TEXT NOT NULL,
            alert_type   TEXT NOT NULL,
            source_ip    TEXT,
            username     TEXT,
            server_name  TEXT,
            description  TEXT,
            details      TEXT,
            status       TEXT DEFAULT 'open',
            created_at   TEXT DEFAULT (datetime('now')),
            updated_at   TEXT DEFAULT (datetime('now'))
        )
    """)

    # -------------------------------------------------------
    # Table: health_checks
    # Stores periodic health check results for VPN servers
    # -------------------------------------------------------
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS health_checks (
            id           INTEGER PRIMARY KEY AUTOINCREMENT,
            server_id    INTEGER NOT NULL,
            server_name  TEXT NOT NULL,
            status       TEXT NOT NULL,
            checked_at   TEXT DEFAULT (datetime('now')),
            response_ms  INTEGER,
            notes        TEXT,
            FOREIGN KEY (server_id) REFERENCES vpn_servers(id)
        )
    """)

    # -------------------------------------------------------
    # Table: settings
    # Stores configurable thresholds and settings
    # -------------------------------------------------------
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS settings (
            key   TEXT PRIMARY KEY,
            value TEXT NOT NULL
        )
    """)

    # Insert default settings if they don't exist
    default_settings = [
        ('failed_login_threshold', '5'),
        ('detection_time_window', '10'),
        ('normal_login_start', '08:00'),
        ('normal_login_end', '22:00'),
        ('multi_username_threshold', '3'),
        ('server_failure_threshold', '3'),
    ]
    for key, value in default_settings:
        cursor.execute(
            "INSERT OR IGNORE INTO settings (key, value) VALUES (?, ?)",
            (key, value)
        )

    conn.commit()
    conn.close()
    logger.info("Database initialized successfully.")


def get_setting(key, default=None):
    """Retrieve a setting value from the database."""
    conn = get_db_connection()
    row = conn.execute("SELECT value FROM settings WHERE key = ?", (key,)).fetchone()
    conn.close()
    return row['value'] if row else default


def set_setting(key, value):
    """Update or insert a setting value in the database."""
    conn = get_db_connection()
    conn.execute(
        "INSERT OR REPLACE INTO settings (key, value) VALUES (?, ?)",
        (key, str(value))
    )
    conn.commit()
    conn.close()
